const DAY = 86400000
const addDays = (ctx, n) => new Date(Date.parse(`${ctx.today}T00:00:00Z`) + n * DAY).toISOString().slice(0, 10)
/** Next date (from tomorrow) falling on the given UTC weekday (0 = Sunday). */
const nextWeekday = (ctx, wd) => {
  for (let i = 1; i <= 7; i += 1) {
    const d = addDays(ctx, i)
    if (new Date(`${d}T00:00:00Z`).getUTCDay() === wd) return d
  }
  return null
}

